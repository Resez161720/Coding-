"""แก้ข้อความจากเครื่องยิง barcode ที่ถูกพิมพ์ผ่านแป้นภาษาไทย (Kedmanee)

เครื่องยิง barcode ส่วนใหญ่ทำตัวเป็นคีย์บอร์ด ถ้า Windows ตั้งภาษาไทยอยู่
"OCT26XY" จะกลายเป็น "ฯฉธ/ุ)ํ" ฟังก์ชันนี้แปลงกลับเป็นปุ่มภาษาอังกฤษเดิม
"""

# ปุ่มบนแป้นอังกฤษ -> ตัวอักษรที่ได้เมื่อแป้นเป็นภาษาไทย (Kedmanee)
_KEDMANEE = {
    "`": "_", "1": "ๅ", "2": "/", "3": "-", "4": "ภ", "5": "ถ",
    "6": "ุ", "7": "ึ", "8": "ค", "9": "ต", "0": "จ",
    "-": "ข", "=": "ช",
    "q": "ๆ", "w": "ไ", "e": "ำ", "r": "พ", "t": "ะ",
    "y": "ั", "u": "ี", "i": "ร", "o": "น", "p": "ย",
    "[": "บ", "]": "ล", "\\": "ฃ",
    "a": "ฟ", "s": "ห", "d": "ก", "f": "ด", "g": "เ",
    "h": "้", "j": "่", "k": "า", "l": "ส", ";": "ว",
    "'": "ง",
    "z": "ผ", "x": "ป", "c": "แ", "v": "อ", "b": "ิ",
    "n": "ื", "m": "ท", ",": "ม", ".": "ใ", "/": "ฝ",
    "~": "%", "!": "+", "@": "๑", "#": "๒", "$": "๓", "%": "๔",
    "^": "ู", "&": "฿", "*": "๕", "(": "๖", ")": "๗",
    "_": "๘", "+": "๙",
    "Q": "๐", "W": '"', "E": "ฎ", "R": "ฑ", "T": "ธ",
    "Y": "ํ", "U": "๊", "I": "ณ", "O": "ฯ", "P": "ญ",
    "{": "ฐ", "}": ",", "|": "ฅ",
    "A": "ฤ", "S": "ฆ", "D": "ฏ", "F": "โ", "G": "ฌ",
    "H": "็", "J": "๋", "K": "ษ", "L": "ศ", ":": "ซ",
    '"': ".",
    "Z": "(", "X": ")", "C": "ฉ", "V": "ฮ", "B": "ฺ",
    "N": "์", "M": "?", "<": "ฒ", ">": "ฬ", "?": "ฦ",
}

_REVERSE = {thai: key for key, thai in _KEDMANEE.items()}


def _has_thai(text: str) -> bool:
    return any("฀" <= ch <= "๿" for ch in text)


def fix_thai_layout(text: str) -> str:
    """คืนข้อความตามปุ่มที่กดจริง ถ้าข้อความมีอักษรไทย (แปลว่าแป้นเป็นภาษาไทยอยู่)"""
    if not _has_thai(text):
        return text
    return "".join(_REVERSE.get(ch, ch) for ch in text)
